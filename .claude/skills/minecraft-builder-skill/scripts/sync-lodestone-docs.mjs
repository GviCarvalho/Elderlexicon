#!/usr/bin/env node

import { execFileSync } from 'node:child_process'
import crypto from 'node:crypto'
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const DOC_FILES = [
  'README.md',
  'getting-started.md',
  'structure.md',
  'nbt.md',
  'rendering.md',
  'resources.md',
  'default-pack-block-states.md',
  'litematic.md',
  'supported-fields.md',
  'unsupported.md',
  'examples.md',
]

const SKILL_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const TARGET_ROOT = path.join(SKILL_ROOT, 'references', 'lodestone')
const SOURCE_JSON = path.join(TARGET_ROOT, '.source.json')
const PACKAGE_NAME = '@mattzh72/lodestone'

function usage() {
  return `Usage:
  node scripts/sync-lodestone-docs.mjs --from <lodestone-repo-or-package> [--check]
  node scripts/sync-lodestone-docs.mjs --check

Examples:
  node scripts/sync-lodestone-docs.mjs --from ../lodestone
  node scripts/sync-lodestone-docs.mjs --from node_modules/@mattzh72/lodestone
  node scripts/sync-lodestone-docs.mjs --from ../lodestone --check
`
}

function parseArgs(argv) {
  const options = {
    from: undefined,
    check: false,
    help: false,
  }

  const readValue = (arg, index) => {
    const value = argv[index + 1]
    if (!value || value.startsWith('-')) throw new Error(`${arg} requires a path`)
    return value
  }

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '-h' || arg === '--help') {
      options.help = true
    } else if (arg === '--check') {
      options.check = true
    } else if (arg === '--from') {
      options.from = readValue(arg, index)
      index += 1
    } else if (arg.startsWith('--from=')) {
      options.from = arg.slice('--from='.length)
    } else {
      throw new Error(`Unexpected argument: ${arg}`)
    }
  }

  return options
}

async function exists(filePath) {
  try {
    await fs.access(filePath)
    return true
  } catch {
    return false
  }
}

function sha256(text) {
  return crypto.createHash('sha256').update(text).digest('hex')
}

function normalizeText(text) {
  return text.replace(/\r\n/g, '\n').replace(/\s+$/u, '') + '\n'
}

function header(version, file) {
  return `<!--
Synced from ${PACKAGE_NAME} docs for version ${version}.
Source file: docs/${file}
Do not edit this file directly. Run scripts/sync-lodestone-docs.mjs.
-->

`
}

async function readJson(filePath) {
  return JSON.parse(await fs.readFile(filePath, 'utf8'))
}

function getExpectedLodestoneVersion(skillPackageJson) {
  const version = skillPackageJson.dependencies?.[PACKAGE_NAME]
  if (!version || /[~^*><=]/.test(version)) {
    throw new Error(`Expected an exact ${PACKAGE_NAME} dependency version in package.json`)
  }
  return version
}

async function resolveSourceRoot(from) {
  const candidates = []
  if (from) {
    candidates.push(path.resolve(SKILL_ROOT, from))
    candidates.push(path.resolve(from))
  } else {
    if (process.env.LODESTONE_DOCS_SOURCE) {
      candidates.push(path.resolve(process.env.LODESTONE_DOCS_SOURCE))
    }
    candidates.push(path.resolve(SKILL_ROOT, '..', 'lodestone'))
    candidates.push(path.resolve(SKILL_ROOT, 'node_modules', PACKAGE_NAME))
  }

  const seen = new Set()
  for (const candidate of candidates) {
    if (seen.has(candidate)) continue
    seen.add(candidate)
    const docsRoot = path.basename(candidate) === 'docs' ? candidate : path.join(candidate, 'docs')
    if (await exists(docsRoot)) {
      const packageRoot = path.basename(candidate) === 'docs' ? path.dirname(candidate) : candidate
      return { packageRoot, docsRoot }
    }
  }

  if (from) throw new Error(`Could not find docs/ under --from path: ${from}`)
  return null
}

function tryGitCommit(packageRoot) {
  try {
    return execFileSync('git', ['-C', packageRoot, 'rev-parse', 'HEAD'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim()
  } catch {
    return null
  }
}

function tryGitDirty(packageRoot) {
  try {
    const status = execFileSync('git', ['-C', packageRoot, 'status', '--porcelain'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    })
    return status.trim().length > 0
  } catch {
    return null
  }
}

async function readSource(source) {
  const packageJson = await readJson(path.join(source.packageRoot, 'package.json'))
  const files = {}
  for (const file of DOC_FILES) {
    const filePath = path.join(source.docsRoot, file)
    if (!(await exists(filePath))) {
      throw new Error(`Missing Lodestone doc: ${filePath}`)
    }
    const content = normalizeText(await fs.readFile(filePath, 'utf8'))
    files[file] = {
      content,
      sourceSha256: sha256(content),
    }
  }
  return {
    version: packageJson.version,
    source: path.relative(SKILL_ROOT, source.docsRoot),
    gitCommit: tryGitCommit(source.packageRoot),
    gitDirty: tryGitDirty(source.packageRoot),
    files,
  }
}

async function syncDocs(sourceData, expectedVersion) {
  if (sourceData.version !== expectedVersion) {
    throw new Error(`${PACKAGE_NAME} docs are version ${sourceData.version}, but skill depends on ${expectedVersion}`)
  }

  await fs.mkdir(TARGET_ROOT, { recursive: true })
  const metadata = {
    package: PACKAGE_NAME,
    version: sourceData.version,
    source: sourceData.source,
    gitCommit: sourceData.gitCommit,
    gitDirty: sourceData.gitDirty,
    syncedAt: new Date().toISOString(),
    files: {},
  }

  for (const file of DOC_FILES) {
    const vendored = header(sourceData.version, file) + sourceData.files[file].content
    await fs.writeFile(path.join(TARGET_ROOT, file), vendored)
    metadata.files[file] = {
      sourceSha256: sourceData.files[file].sourceSha256,
      vendoredSha256: sha256(vendored),
    }
  }

  await fs.writeFile(SOURCE_JSON, `${JSON.stringify(metadata, null, 2)}\n`)
  console.log(`Synced ${DOC_FILES.length} Lodestone docs to ${path.relative(SKILL_ROOT, TARGET_ROOT)}`)
}

async function readMetadata() {
  if (!(await exists(SOURCE_JSON))) {
    throw new Error(`Missing ${path.relative(SKILL_ROOT, SOURCE_JSON)}. Run docs sync first.`)
  }
  return readJson(SOURCE_JSON)
}

async function checkVendoredHashes(metadata) {
  const errors = []
  for (const file of DOC_FILES) {
    const filePath = path.join(TARGET_ROOT, file)
    if (!(await exists(filePath))) {
      errors.push(`Missing vendored doc: ${file}`)
      continue
    }
    const content = await fs.readFile(filePath, 'utf8')
    const actual = sha256(content)
    const expected = metadata.files?.[file]?.vendoredSha256
    if (actual !== expected) {
      errors.push(`Vendored doc hash mismatch: ${file}`)
    }
  }
  return errors
}

async function checkDocs(sourceData, expectedVersion) {
  const metadata = await readMetadata()
  const errors = []

  if (metadata.package !== PACKAGE_NAME) {
    errors.push(`Expected metadata package ${PACKAGE_NAME}, found ${metadata.package}`)
  }
  if (metadata.version !== expectedVersion) {
    errors.push(`Skill depends on ${expectedVersion}, but vendored docs are ${metadata.version}`)
  }
  if (sourceData && sourceData.version !== expectedVersion) {
    errors.push(`Source docs are ${sourceData.version}, but skill depends on ${expectedVersion}`)
  }

  errors.push(...await checkVendoredHashes(metadata))

  if (sourceData) {
    for (const file of DOC_FILES) {
      const expectedSourceHash = metadata.files?.[file]?.sourceSha256
      const actualSourceHash = sourceData.files[file]?.sourceSha256
      if (actualSourceHash !== expectedSourceHash) {
        errors.push(`Source doc hash mismatch: ${file}`)
      }
      const expectedVendored = header(sourceData.version, file) + sourceData.files[file].content
      const vendoredPath = path.join(TARGET_ROOT, file)
      const actualVendored = await fs.readFile(vendoredPath, 'utf8').catch(() => '')
      if (actualVendored !== expectedVendored) {
        errors.push(`Vendored doc content is not synced from source: ${file}`)
      }
    }
  }

  const metadataFiles = Object.keys(metadata.files ?? {})
  for (const file of metadataFiles) {
    if (!DOC_FILES.includes(file)) errors.push(`Unexpected vendored doc in metadata: ${file}`)
  }

  if (errors.length > 0) {
    throw new Error(`Lodestone docs are out of sync:\n- ${errors.join('\n- ')}`)
  }

  console.log(`Lodestone docs are in sync for ${PACKAGE_NAME}@${expectedVersion}`)
}

async function main() {
  const options = parseArgs(process.argv.slice(2))
  if (options.help) {
    console.log(usage())
    return
  }

  const skillPackageJson = await readJson(path.join(SKILL_ROOT, 'package.json'))
  const expectedVersion = getExpectedLodestoneVersion(skillPackageJson)
  const source = await resolveSourceRoot(options.from)
  const sourceData = source ? await readSource(source) : null

  if (options.check) {
    await checkDocs(sourceData, expectedVersion)
  } else {
    if (!sourceData) {
      throw new Error('Sync requires --from or an available Lodestone docs source')
    }
    await syncDocs(sourceData, expectedVersion)
  }
}

main().catch(error => {
  console.error(`sync-lodestone-docs: ${error.message}`)
  process.exitCode = 1
})
