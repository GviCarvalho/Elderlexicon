def compose(ch):
    """Os traços de uma letra, já com o acento, se for acentuada."""
    if ch in LETTERS:
        return LETTERS[ch]
    base, accent = COMPOSED[ch]
    strokes, dots = LETTERS[base]
    xs = [x for st in strokes for x, _ in (st[1] if isinstance(st, tuple) else st)]
    cx = (min(xs) + max(xs)) / 2
    top = 1.9 if base.islower() or base == "ı" else -1.0
    a_strokes, a_dots = ACCENTS[accent]
    moved = [[(x + cx, y + top) for x, y in st] for st in a_strokes]
    return strokes + moved, dots + [(x + cx, y + top) for x, y in a_dots]


