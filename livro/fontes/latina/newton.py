def compose(ch):
    if ch in LETTERS:
        return LETTERS[ch]
    if ch in LIGATURES:
        return LIGATURES[ch]
    if ch in ABBREVIATIONS:
        return ABBREVIATIONS[ch]
    base, accent = COMPOSED[ch]
    strokes, dots = LETTERS[base]
    xs = [x for st in strokes for x, _ in (st[1] if isinstance(st, tuple) else st)]
    cx = (min(xs) + max(xs)) / 2
    top = 2.5 if base.islower() or base == "ı" else -1.0
    a_strokes, a_dots = ACCENTS[accent]
    return (strokes + [[(x + cx, y + top) for x, y in st] for st in a_strokes],
            dots + [(x + cx, y + top) for x, y in a_dots])


def shape(word, abbreviations=True):
    """Divide uma palavra nas unidades que a fonte desenha: letras, ligaduras e abreviações."""
    if abbreviations and word.lower() in ABBREVIATIONS and word.islower():
        return [word]
    out, i = [], 0
    while i < len(word):
        pair = word[i:i + 2]
        if pair in LIGATURES:
            out.append(pair)
            i += 2
        else:
            out.append(word[i])
            i += 1
    return out
